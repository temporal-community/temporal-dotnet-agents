"""Extract copyable outer-activity examples verbatim for the compile-only harness."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[3]
EXAMPLES = (
    ("Usage", "docs/how-to/MAF/usage.md", "Parallel Agent Execution", None),
    ("Routing", "docs/how-to/MAF/routing.md", "Static routing", None),
    ("Routing", "docs/how-to/MAF/routing.md", "Dynamic routing through a registry activity", None),
    ("Invocation", "docs/how-to/MAF/dos-and-donts.md", "Do invoke registered agents through activities",
     "internal static async Task RunAsync(string prompt)"),
    ("Configuration", "docs/how-to/MAF/dos-and-donts.md",
     "Do configure the activity that invokes the registered agent",
     "internal static async Task RunAsync(TemporalAgentSessionId sessionId, string requestId, string prompt)"),
    ("PromptCaching", "docs/how-to/MAF/prompt-caching.md", "2. Summarize History Before Sending", None),
    ("Sequential", "docs/architecture/MAF/agent-to-agent-communication.md", "Sequential Calls",
     "internal static async Task RunAsync(string topic)"),
    ("Parallel", "docs/architecture/MAF/agent-to-agent-communication.md", "Parallel Fan-Out",
     "internal static async Task RunAsync(string topic)"),
    ("Events", "docs/architecture/MAF/pub-sub-and-event-driven.md",
     "Code Example — Fan-Out / Fan-In with Activities", None),
    ("Combinations", "docs/library-combinations.md", "Workflow orchestration usage", None),
    ("Determinism", "docs/architecture/MAF/durability-and-determinism.md",
     "Calling a Registered Agent from a Workflow", None),
)


def main():
    usings = {
        "using DocSnippets.Harness;",
        "using Microsoft.Extensions.DependencyInjection;",
        "using TemporalCommunity.Extensions.Agents;",
        "using TemporalCommunity.Extensions.Agents.Session;",
        "using Temporalio.Activities;",
        "using Temporalio.Common;",
        "using Temporalio.Workflows;",
        "using RoutingActivities = DocSnippets.Generated.AgentInvocations.Routing.RoutingActivities;",
    }
    containers = {}
    for container, path, heading, wrapper in EXAMPLES:
        text = (ROOT / path).read_text()
        # Ignore headings inside fences, and fail closed on missing/ambiguous headings or blocks.
        sections = {}
        current = None
        fenced = False
        for line in text.splitlines():
            if line.startswith("```"):
                fenced = not fenced
            match = re.match(r"^#{1,6} (.+)$", line) if not fenced else None
            if match:
                current = match[1]
                if current == heading and current in sections:
                    raise ValueError(f"Duplicate heading: {path}#{current}")
                sections[current] = []
            elif current is not None:
                sections[current].append(line)
        blocks = re.findall(r"```csharp\n(.*?)```", "\n".join(sections[heading]), re.DOTALL)
        if len(blocks) != 1:
            raise ValueError(f"Expected one C# block: {path}#{heading}, found {len(blocks)}")
        lines = blocks[0].splitlines()
        while lines and (not lines[0].strip() or lines[0].startswith("using ")):
            if lines[0].startswith("using "):
                usings.add(lines[0])
            lines.pop(0)
        code = "\n".join(lines)
        if wrapper:
            code = wrapper + "\n{\n" + code + "\n}"
        containers.setdefault(container, []).append(f"// {path} — {heading}\n{code}")

    source = "// <auto-generated/>\n" + "\n".join(sorted(usings))
    source += "\n\nnamespace DocSnippets.Generated.AgentInvocations;\n"
    for container, examples in containers.items():
        # Prompt caching documents a workflow method rather than a complete class.
        declaration = "[Workflow]\ninternal class" if container == "PromptCaching" else "internal static class"
        source += f"\n{declaration} {container}\n{{\n" + "\n\n".join(examples) + "\n}\n"
    output = Path(sys.argv[1])
    if len(sys.argv) > 2 and sys.argv[2] == "--check":
        if not output.exists() or output.read_text() != source:
            raise SystemExit(f"Generated examples are stale: {output}")
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != source:
        output.write_text(source)


if __name__ == "__main__":
    main()
